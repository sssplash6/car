// Turn a drawing made in a vector editor into a Contour data module (DESIGN.md §5.2).
//
//   node scripts/illustration-prep.mjs in.svg tulip > src/app/_components/illustrations/data/tulip.ts
//
// Export the SVG flat first: strokes only, round caps, each visual stroke its
// own <path>, dots as <circle>, no transforms, absolute path commands. Document
// order is draw order. A path may carry data-stage="1|2|3" (About's tulip).
// Then register the name in illustrations/index.ts and types.ts.
//
// No dependencies on purpose: regex over a flat SVG is enough for this shape.
import { readFileSync } from "node:fs";

const [, , file, name] = process.argv;
if (!file || !name) {
  console.error("usage: node scripts/illustration-prep.mjs in.svg name > out.ts");
  process.exit(1);
}

const svg = readFileSync(file, "utf8");
if (/\stransform=/.test(svg)) {
  console.error("The SVG still has transforms. Flatten them in the editor and export again.");
  process.exit(1);
}

const viewBox = svg.match(/viewBox="([^"]+)"/)?.[1].trim().split(/[\s,]+/).map(Number);
if (!viewBox || viewBox.length !== 4) {
  console.error("No viewBox found.");
  process.exit(1);
}

const attr = (tag, key) => tag.match(new RegExp(`\\s${key}="([^"]+)"`))?.[1];

const strokes = [...svg.matchAll(/<path\b[^>]*>/g)].map(([tag]) => {
  const d = attr(tag, "d");
  if (!d) throw new Error(`path without d: ${tag}`);
  if (/[a-z]/.test(d.replace(/e-?\d/g, ""))) {
    throw new Error("Relative path commands found; export with absolute coordinates.");
  }
  const stage = attr(tag, "data-stage");
  return stage ? { d: d.replace(/\s+/g, " ").trim(), stage: Number(stage) } : { d: d.replace(/\s+/g, " ").trim() };
});

const dots = [...svg.matchAll(/<circle\b[^>]*>/g)].map(([tag]) => {
  const dot = ["cx", "cy", "r"].map((key) => Number(attr(tag, key)));
  const stage = attr(tag, "data-stage");
  return stage ? [...dot, Number(stage)] : dot;
});

if (strokes.length > 14) console.error(`warning: ${strokes.length} strokes (budget 14)`);
if (dots.length > 9) console.error(`warning: ${dots.length} dots (budget 9)`);

const data = { viewBox: [viewBox[2], viewBox[3]], strokes, dots };
process.stdout.write(
  [
    `// Generated by scripts/illustration-prep.mjs from ${file.split("/").pop()}.`,
    'import type { DrawingData } from "../types";',
    "",
    `export const ${name}: DrawingData = ${JSON.stringify(data, null, 2)};`,
    "",
  ].join("\n"),
);
